"""Compare extraction model output against reference labels on the overlap
of the 150-review label_sample.

This is model-to-model agreement: a cheap extraction model (config.EXTRACTION_MODEL)
against reference labels generated by Claude in a chat session
(labeler="claude-chat-reference", see src/import_reference_labels.py). It is
NOT agreement with a human-verified gold standard -- never describe it that
way in README.md, CLAUDE.md, or anywhere else this script's output is used.

Computes, over reviews with both a reference label and an extraction result:
- category agreement (accuracy) and Cohen's kappa
- per-category precision/recall
- confusion matrix (reference rows x extraction columns)
- severity agreement (exact-match rate and mean absolute difference, among
  reviews where both sides assigned a non-null severity)

Usage:
    python -m src.agreement
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict

import duckdb

from src import config, taxonomy as taxonomy_mod


def fetch_pairs(con: duckdb.DuckDBPyConnection) -> list[tuple]:
    return con.execute(
        """
        SELECT l.review_id, l.complaint_category, l.severity,
               e.complaint_category, e.severity
        FROM labels l
        JOIN extractions e ON l.review_id = e.review_id
        WHERE l.labeler = 'claude-chat-reference' AND e.model = ?
        """,
        [config.EXTRACTION_MODEL],
    ).fetchall()


def cohens_kappa(pairs: list[tuple[str, str]]) -> float:
    n = len(pairs)
    if n == 0:
        return float("nan")
    po = sum(1 for ref, ext in pairs if ref == ext) / n
    ref_counts = Counter(ref for ref, _ in pairs)
    ext_counts = Counter(ext for _, ext in pairs)
    categories = set(ref_counts) | set(ext_counts)
    pe = sum((ref_counts.get(c, 0) / n) * (ext_counts.get(c, 0) / n) for c in categories)
    if pe == 1:
        return 1.0
    return (po - pe) / (1 - pe)


def confusion_matrix(pairs: list[tuple[str, str]], categories: list[str]) -> dict[str, dict[str, int]]:
    matrix = {ref: {ext: 0 for ext in categories} for ref in categories}
    for ref, ext in pairs:
        matrix[ref][ext] += 1
    return matrix


def precision_recall(pairs: list[tuple[str, str]], categories: list[str]) -> dict[str, dict[str, float]]:
    result = {}
    for cat in categories:
        tp = sum(1 for ref, ext in pairs if ref == cat and ext == cat)
        fp = sum(1 for ref, ext in pairs if ref != cat and ext == cat)
        fn = sum(1 for ref, ext in pairs if ref == cat and ext != cat)
        precision = tp / (tp + fp) if (tp + fp) else float("nan")
        recall = tp / (tp + fn) if (tp + fn) else float("nan")
        result[cat] = {"precision": precision, "recall": recall, "support": sum(1 for ref, _ in pairs if ref == cat)}
    return result


def severity_agreement(rows: list[tuple]) -> dict:
    both_scored = [(ref_sev, ext_sev) for _, _, ref_sev, _, ext_sev in rows if ref_sev is not None and ext_sev is not None]
    if not both_scored:
        return {"n": 0, "exact_match_rate": float("nan"), "mean_abs_diff": float("nan")}
    exact = sum(1 for r, e in both_scored if r == e)
    mean_abs_diff = sum(abs(r - e) for r, e in both_scored) / len(both_scored)
    return {
        "n": len(both_scored),
        "exact_match_rate": exact / len(both_scored),
        "mean_abs_diff": mean_abs_diff,
    }


def main() -> None:
    if not config.DUCKDB_PATH.exists():
        raise SystemExit(f"{config.DUCKDB_PATH} not found.")

    con = duckdb.connect(str(config.DUCKDB_PATH), read_only=True)
    rows = fetch_pairs(con)
    con.close()

    if not rows:
        raise SystemExit(
            "No overlapping (reference label, extraction) pairs found. "
            "Run import_reference_labels.py and extract.py --target label_sample first."
        )

    categories = sorted(taxonomy_mod.valid_category_keys())
    category_pairs = [(ref_cat, ext_cat) for _, ref_cat, _, ext_cat, _ in rows]

    n = len(category_pairs)
    accuracy = sum(1 for ref, ext in category_pairs if ref == ext) / n
    kappa = cohens_kappa(category_pairs)
    pr = precision_recall(category_pairs, categories)
    matrix = confusion_matrix(category_pairs, categories)
    sev = severity_agreement(rows)

    stats = {
        "model": config.EXTRACTION_MODEL,
        "n_pairs": n,
        "category_accuracy": accuracy,
        "cohens_kappa": kappa,
        "precision_recall": pr,
        "confusion_matrix": matrix,
        "severity_agreement": sev,
    }
    config.AGREEMENT_STATS_PATH.write_text(json.dumps(stats, indent=2))

    print(f"Model-to-model agreement: {config.EXTRACTION_MODEL} vs. claude-chat-reference")
    print(f"(reference labels are AI-generated, not human -- see CLAUDE.md)")
    print(f"\nPairs compared: {n}")
    print(f"Category accuracy: {accuracy:.3f}")
    print(f"Cohen's kappa: {kappa:.3f}")

    print(f"\nSeverity agreement (n={sev['n']}, both sides scored):")
    print(f"  exact match rate: {sev['exact_match_rate']:.3f}" if sev["n"] else "  (no overlapping scored pairs)")
    if sev["n"]:
        print(f"  mean absolute difference: {sev['mean_abs_diff']:.3f}")

    print("\nPer-category precision/recall (support = # reference labels in that category):")
    for cat in categories:
        p = pr[cat]
        if p["support"] == 0 and p["precision"] != p["precision"]:  # nan check, never predicted either
            continue
        print(f"  {cat:20s} precision={p['precision']:.3f}  recall={p['recall']:.3f}  support={p['support']}")

    print("\nConfusion matrix (rows=reference, cols=extracted):")
    header = "reference\\extracted".ljust(20) + "".join(c[:10].rjust(12) for c in categories)
    print(header)
    for ref_cat in categories:
        row = matrix[ref_cat]
        if sum(row.values()) == 0:
            continue
        print(ref_cat.ljust(20) + "".join(str(row[c]).rjust(12) for c in categories))

    print(f"\nWrote {config.AGREEMENT_STATS_PATH}")


if __name__ == "__main__":
    main()
