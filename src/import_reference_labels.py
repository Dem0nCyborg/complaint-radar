"""Import reference labels for the 150-review label_sample from a CSV.

Reference labels for this project are NOT from a human annotator and are
NOT produced by calling a model API from this repo. They're generated by
Claude in a separate chat session (given data/interim/label_sample_export.csv
as input), then brought back as a CSV and imported here. The metric computed
against them (src/agreement.py) is model-to-model agreement: a cheap
extraction model compared against a stronger model's judgment, not a human
gold standard. See README.md and CLAUDE.md.

Expected input: data/interim/reference_labels.csv with columns
review_id, complaint_category, severity, note. severity must be 1-3 for
every category except no_complaint, which must be blank/NULL. Every
category must be a key in config/categories.yaml, and every review_id must
be one of the 150 in label_sample.

Validates the whole file before writing anything -- on any error, nothing
is written and every problem found is listed (not just the first one).

Usage:
    python -m src.import_reference_labels [--csv PATH]
"""

from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
from pathlib import Path

import duckdb
import yaml

from src import config

LABELER_NAME = "claude-chat-reference"
NULL_TOKENS = {"", "null", "none"}


def load_taxonomy() -> dict:
    return yaml.safe_load(config.CATEGORIES_YAML_PATH.read_text())


def validate_rows(rows: list[dict], valid_categories: set[str]) -> tuple[list[tuple], list[str]]:
    parsed = []
    errors = []
    seen_ids: set[str] = set()

    for i, row in enumerate(rows, start=2):  # header is line 1
        review_id = (row.get("review_id") or "").strip()
        category = (row.get("complaint_category") or "").strip()
        severity_raw = (row.get("severity") or "").strip()
        note = (row.get("note") or "").strip() or None

        if not review_id:
            errors.append(f"line {i}: missing review_id")
            continue
        if review_id in seen_ids:
            errors.append(f"line {i}: duplicate review_id {review_id}")
            continue
        seen_ids.add(review_id)

        if category not in valid_categories:
            errors.append(f"line {i} ({review_id}): '{category}' is not a category in categories.yaml")
            continue

        if category == "no_complaint":
            if severity_raw.lower() not in NULL_TOKENS:
                errors.append(f"line {i} ({review_id}): severity must be blank for no_complaint, got '{severity_raw}'")
                continue
            severity = None
        else:
            if severity_raw not in ("1", "2", "3"):
                errors.append(f"line {i} ({review_id}): severity must be 1, 2, or 3 for '{category}', got '{severity_raw}'")
                continue
            severity = int(severity_raw)

        if category == "other" and not note:
            errors.append(f"line {i} ({review_id}): category 'other' requires a note")
            continue

        parsed.append((review_id, category, severity, note))

    return parsed, errors


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", default=str(config.INTERIM_DIR / "reference_labels.csv"))
    args = parser.parse_args()

    csv_path = Path(args.csv)
    if not csv_path.exists():
        raise SystemExit(f"{csv_path} not found.")
    if not config.DUCKDB_PATH.exists():
        raise SystemExit(f"{config.DUCKDB_PATH} not found. Run the pipeline through load_duckdb.py first.")

    taxonomy = load_taxonomy()
    valid_categories = {c["key"] for c in taxonomy["categories"]}

    with open(csv_path, newline="", encoding="utf-8") as f:
        raw_rows = list(csv.DictReader(f))

    parsed, errors = validate_rows(raw_rows, valid_categories)

    con = duckdb.connect(str(config.DUCKDB_PATH))
    sample_ids = {r[0] for r in con.execute("SELECT review_id FROM label_sample").fetchall()}

    for review_id, *_ in parsed:
        if review_id not in sample_ids:
            errors.append(f"{review_id}: not one of the 150 review_ids in label_sample")

    if errors:
        con.close()
        print(f"{len(errors)} validation error(s) -- nothing written:")
        for e in errors[:50]:
            print(f"  - {e}")
        if len(errors) > 50:
            print(f"  ... and {len(errors) - 50} more")
        raise SystemExit(1)

    now = datetime.now(timezone.utc)
    con.execute("DELETE FROM labels WHERE labeler = ?", [LABELER_NAME])
    con.executemany(
        """
        INSERT INTO labels (review_id, complaint_category, severity, note, labeler, labeled_at)
        VALUES (?, ?, ?, ?, ?, ?)
        """,
        [(rid, cat, sev, note, LABELER_NAME, now) for rid, cat, sev, note in parsed],
    )
    n_sample = len(sample_ids)
    con.close()

    print(f"Imported {len(parsed)} reference labels (labeler={LABELER_NAME}).")
    if len(parsed) < n_sample:
        print(f"Note: {n_sample - len(parsed)} of {n_sample} label_sample reviews have no reference label yet.")


if __name__ == "__main__":
    main()
